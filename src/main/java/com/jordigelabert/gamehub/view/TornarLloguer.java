private void carregarLloguers() {

    DefaultTableModel model =
            (DefaultTableModel) taulaLloguers.getModel();

    model.setRowCount(0);
    lloguersTaula.clear();

    List<Lloguer> lloguers = new ArrayList<>(gestio.getLloguers());

    // Ordenar per número de registre descendent
    lloguers.sort(
            Comparator.comparingInt(Lloguer::getId).reversed()
    );

    for (Lloguer lloguer : lloguers) {

        // Mostrar només els lloguers actius
        if (!lloguer.estaActiu()) {
            continue;
        }

        lloguersTaula.add(lloguer);

        model.addRow(new Object[]{
            String.format("%02d", lloguer.getId()),
            lloguer.getVideojoc().getNom(),
            lloguer.getUsuari().getNomComplet(),
            lloguer.getPlataforma() == Plataforma.SWITCH_2
                    ? "Switch 2"
                    : lloguer.getPlataforma().toString(),
            lloguer.getDataInici().format(FORMAT_DATA)
        });
    }

    taulaLloguers.clearSelection();
    actualitzarDetalls();
}

private void actualitzarDetalls() {

    int fila = taulaLloguers.getSelectedRow();

    if (fila < 0) {
        valorJoc.setText("-");
        valorUsuari.setText("-");
        valorPlataforma.setText("-");
        valorDataInici.setText("-");

        botoRetornar.setEnabled(false);
        return;
    }

    int filaModel = taulaLloguers.convertRowIndexToModel(fila);

    Lloguer lloguer = lloguersTaula.get(filaModel);

    valorJoc.setText(lloguer.getVideojoc().getNom());
    valorUsuari.setText(lloguer.getUsuari().getNomComplet());

    valorPlataforma.setText(
            lloguer.getPlataforma() == Plataforma.SWITCH_2
                    ? "Switch 2"
                    : lloguer.getPlataforma().toString()
    );

    valorDataInici.setText(
            lloguer.getDataInici().format(FORMAT_DATA)
    );

    botoRetornar.setEnabled(true);
}

