    private void botoRetornarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoRetornarActionPerformed
        // TODO add your handling code here:
        int fila = taulaLloguers.getSelectedRow();

if (fila < 0) {
    return;
}

int filaModel = taulaLloguers.convertRowIndexToModel(fila);
Lloguer lloguer = lloguersTaula.get(filaModel);

// Confirmar la devolució
int resposta = JOptionPane.showConfirmDialog(
        this,
        "Vols marcar aquest lloguer com a retornat?",
        "Confirmar devolució",
        JOptionPane.YES_NO_OPTION
);

if (resposta != JOptionPane.YES_OPTION) {
    return;
}

// Registrar la devolució
if (gestio.retornarLloguer(lloguer)) {

    JOptionPane.showMessageDialog(
            this,
            "El lloguer s'ha retornat correctament."
    );

    carregarLloguers();

} else {

    JOptionPane.showMessageDialog(
            this,
            "Aquest lloguer ja ha estat retornat.",
            "Error",
            JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_botoRetornarActionPerformed

