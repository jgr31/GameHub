    private void carregarLloguers() {

    DefaultTableModel model =
            (DefaultTableModel) taulaLloguers.getModel();

    model.setRowCount(0);

    DateTimeFormatter format =
            DateTimeFormatter.ofPattern("dd/MM/yyyy");

    for (int i = gestio.getLloguers().size() - 1; i >= 0; i--) {

        Lloguer lloguer = gestio.getLloguers().get(i);

        String estat;

        if (lloguer.isRetornat()) {
            estat = "Retornat";
        } else if (lloguer.estaVencut()) {
            estat = "Vençut";
        } else {
            estat = "Actiu";
        }

        model.addRow(new Object[]{
            lloguer.getId(),
            lloguer.getVideojoc().getNom(),
            lloguer.getUsuari().getNomComplet(),
            lloguer.getPlataforma() == com.jordigelabert.gamehub.model.Plataforma.SWITCH_2
                ? "Switch 2"
                : lloguer.getPlataforma().toString(),
            lloguer.getDataInici().format(format),
            lloguer.getDataRetornPrevista().format(format),
            lloguer.getVideojoc().getGenere(),
            estat
        });
    }
    
    labelTotalLloguers.setText(
        "Total de lloguers: " + gestio.getLloguers().size()
);
}

    private void configurarColorsTaula() {

    taulaLloguers.setDefaultRenderer(
            Object.class,
            new DefaultTableCellRenderer() {

        @Override
        public Component getTableCellRendererComponent(
                JTable table, Object value, boolean isSelected,
                boolean hasFocus, int row, int column) {

            Component component = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column
            );

            int filaModel = table.convertRowIndexToModel(row);

            String estat = table.getModel()
                    .getValueAt(filaModel, 7).toString();

            if (isSelected) {
                component.setBackground(table.getSelectionBackground());
                component.setForeground(table.getSelectionForeground());

            } else {
                component.setForeground(Color.BLACK);

                switch (estat) {
                    case "Retornat":
                        component.setBackground(new Color(190, 245, 205));
                        break;

                    case "Vençut":
                        component.setBackground(new Color(255, 195, 195));
                        break;

                    default:
                        component.setBackground(Color.WHITE);
                        break;
                }
            }

            return component;
        }
    });
}
    
