    private void botoEsborrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoEsborrarActionPerformed
        // TODO add your handling code here:
        Usuari usuari = (Usuari) comboUsuari.getSelectedItem();

if (usuari == null) {
    JOptionPane.showMessageDialog(
            this,
            textos.getString("usuari.esborrar.cap")
    );
    return;
}

// Demanar confirmació
int resposta = JOptionPane.showConfirmDialog(
        this,
        textos.getString("usuari.esborrar.confirmacio"),
        textos.getString("usuari.esborrar.titol"),
        JOptionPane.YES_NO_OPTION
);

if (resposta != JOptionPane.YES_OPTION) {
    return;
}

// Intentar eliminar
if (gestio.eliminarUsuari(usuari)) {

    JOptionPane.showMessageDialog(
            this,
            textos.getString("usuari.esborrar.correcte")
    );

    dispose();

} else {

    JOptionPane.showMessageDialog(
            this,
            textos.getString("usuari.esborrar.bloquejat"),
            textos.getString("missatge.error"),
            JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_botoEsborrarActionPerformed

