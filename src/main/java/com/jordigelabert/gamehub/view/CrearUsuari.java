    private void botoConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoConfirmarActionPerformed
        // TODO add your handling code here:
        String nom = campNom.getText().trim();
String llinatge1 = campLlinatge1.getText().trim();
String llinatge2 = campLlinatge2.getText().trim();
String dni = campDni.getText().trim();
String telefon = campTelefon.getText().trim();

// Comprovar camps obligatoris
if (!Validacions.campObligatori(nom)
        || !Validacions.campObligatori(llinatge1)
        || !Validacions.campObligatori(llinatge2)
        || !Validacions.campObligatori(dni)
        || !Validacions.campObligatori(telefon)) {

    mostrarError("error.campsObligatoris");
    return;
}

// Comprovar majúscula inicial
if (!Validacions.nomComencaMajuscula(nom)) {
    mostrarError("error.nomMajuscula");
    return;
}

// Validar telèfon
if (!Validacions.telefonValid(telefon)) {
    mostrarError("error.telefon");
    return;
}

// Validar DNI
if (!Validacions.dniValid(dni)) {
    mostrarError("error.dni");
    return;
}

// Crear usuari
gestio.crearUsuari(nom, llinatge1, llinatge2, dni, telefon);

JOptionPane.showMessageDialog(
        this,
        textos.getString("missatge.usuariCreat"),
        textos.getString("usuari.titol"),
        JOptionPane.INFORMATION_MESSAGE
);

dispose();
    }//GEN-LAST:event_botoConfirmarActionPerformed

