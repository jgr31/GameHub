private void actualitzarSpinner(
        javax.swing.JCheckBox check,
        javax.swing.JSpinner spinner) {

    boolean seleccionat = check.isSelected();

    spinner.setEnabled(seleccionat);

    if (!seleccionat) {
        spinner.setValue(0);
    }
}
    

