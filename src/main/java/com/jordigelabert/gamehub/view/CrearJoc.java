    private void botoConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botoConfirmarActionPerformed
        // TODO add your handling code here:
        
        String nom = campNom.getText().trim();
String genere = comboGenere.getSelectedItem().toString();

// Validar nom
if (!Validacions.campObligatori(nom)) {
    mostrarError("error.jocNom");
    return;
}

// Validar que hi hagi alguna plataforma seleccionada
if (!checkPS5.isSelected()
        && !checkXbox.isSelected()
        && !checkPC.isSelected()
        && !checkSwitch2.isSelected()) {

    mostrarError("error.jocPlataforma");
    return;
}

// Obtenir unitats
int ps5 = (Integer) spinnerPS5.getValue();
int xbox = (Integer) spinnerXbox.getValue();
int pc = (Integer) spinnerPC.getValue();
int switch2 = (Integer) spinnerSwitch2.getValue();

// Validar unitats
if ((checkPS5.isSelected() && ps5 <= 0)
        || (checkXbox.isSelected() && xbox <= 0)
        || (checkPC.isSelected() && pc <= 0)
        || (checkSwitch2.isSelected() && switch2 <= 0)) {

    mostrarError("error.jocUnitats");
    return;
}

// Crear videojoc
Videojoc videojoc = gestio.crearVideojoc(nom, genere);

// Assignar estoc
videojoc.establirEstoc(Plataforma.PS5, ps5);
videojoc.establirEstoc(Plataforma.XBOX, xbox);
videojoc.establirEstoc(Plataforma.PC, pc);
videojoc.establirEstoc(Plataforma.SWITCH_2, switch2);

// Confirmació
JOptionPane.showMessageDialog(
        this,
        textos.getString("missatge.jocCreat"),
        textos.getString("joc.titol"),
        JOptionPane.INFORMATION_MESSAGE
);

dispose();
        
    }//GEN-LAST:event_botoConfirmarActionPerformed

